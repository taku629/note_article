def apply_replacements(text: str, replacements: list) -> tuple[str, list]:
    """
    テキストに置換ルールを順番に適用する。
    変更があった置換ルールを記録して返す。
    """
    changed = []
    for old, new in replacements:
        if old in text:
            text = text.replace(old, new)
            changed.append((old, new))
    return text, changed


def process_all():
    total_changes = 0
    file_summaries = []

    for filepath in sorted(ARTICLES_DIR.glob("*.md"), key=lambda p: (
        [int(x) if x.isdigit() else x for x in re.split(r"(\d+)", p.name)]
    )):
        original = filepath.read_text(encoding="utf-8")
        modified, changed = apply_replacements(original, REPLACEMENTS)

        if changed:
            filepath.write_text(modified, encoding="utf-8")
            total_changes += len(changed)
            file_summaries.append((filepath.name, len(changed), changed))

    # 結果表示
    print(f"修正ファイル数: {len(file_summaries)} / 47")
    print(f"総置換回数: {total_changes}")
    print()
    for fname, count, changes in file_summaries:
        print(f"【{fname}】{count}件")
        for old, new in changes:
            print(f"  「{old[:30]}」→「{new[:30]}」")
        print()


if __name__ == "__main__":
    process_all()
